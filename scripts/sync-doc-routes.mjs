// Generates unlisted compatibility pages for moved documents and the ownership
// table in development/doc-structure.mdx from project/doc-routes.json.
// The map records document ownership and URL history only; it is not a
// physical specification registry.
import { readFile, writeFile, mkdir, realpath } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const GENERATED_MARK = '{/* GENERATED: node scripts/sync-doc-routes.mjs / project/doc-routes.json */}';
const TABLE_BEGIN = '{/* DOC-ROUTES-BEGIN: generated by scripts/sync-doc-routes.mjs */}';
const TABLE_END = '{/* DOC-ROUTES-END */}';
export const OWNER_LABELS = {
  overview: '全体案内',
  'metal-case': '金属ケース',
  'printed-5mm': '家庭印刷ケース',
  'tenbox-v2': '10BOX-v2',
  'two-way': '2WAY 実験設計',
  shared: '共通部品・元データ',
  development: '開発・保守',
};
export const TREATMENT_LABELS = {
  retained: '維持',
  moved: '移動',
  'moved-historical': '移動・履歴',
  split: '分割',
  new: '新規',
};

export function routeFor(source) {
  let p = source.replace(/\.mdx$/, '');
  if (p.endsWith('/index')) p = p.slice(0, -'/index'.length);
  return `/docs/${p}/`;
}

export function frontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const data = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^([a-z_]+):\s*(.+)$/);
    if (!m) continue;
    try { data[m[1]] = JSON.parse(m[2]); } catch { data[m[1]] = m[2]; }
  }
  return data;
}

// Compatibility pages exist where a source path no longer holds the canonical page.
export function isCompatibility(entry) {
  return entry.source !== null && entry.source !== entry.canonical;
}

export function anchorTarget(entry, anchor) {
  return entry.anchorTargets?.[anchor] ?? `${entry.canonical}#${anchor}`;
}

function relativeLink(fromSource, target) {
  const [file, hash] = target.split('#');
  let rel = path.posix.relative(path.posix.dirname(fromSource), file);
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return hash === undefined ? rel : `${rel}#${hash.replace(/[()<>\s]/g, c => encodeURIComponent(c))}`;
}

const escapeText = s => s.replace(/[{}<>|]/g, c => `\\${c}`);
const escapeAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

export function renderCompatibilityPage(entry, canonicalTitle) {
  const destination = relativeLink(entry.source, entry.canonical);
  const lines = [
    '---',
    `title: ${JSON.stringify(`${canonicalTitle}（移動済み）`)}`,
    `description: ${JSON.stringify(`旧URLの互換ページ。正式なページは${routeFor(entry.canonical)}。`)}`,
    'sidebar_position: 999',
    'unlisted: true',
    '---',
    '',
    GENERATED_MARK,
    '',
    ':::note[このページは移動しました]',
    '',
    `正式なページ: **[${escapeText(canonicalTitle)}](${destination})**`,
    '',
    '旧URLを残すための互換ページです。本文は移動先だけで管理します。',
    '',
    ':::',
  ];
  const anchors = entry.anchors ?? [];
  if (anchors.length) {
    lines.push('', '| 旧URLの見出しアンカー | 移動先 |', '|---|---|');
    for (const anchor of anchors) {
      const target = anchorTarget(entry, anchor);
      lines.push(`| <span id="${escapeAttr(anchor)}"></span>\`#${anchor}\` | [${escapeText(anchor)}](${relativeLink(entry.source, target)}) |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

export function renderOwnershipTable(map, titles) {
  const rows = ['| 旧URL | 所有 | 正式なページ | 扱い |', '|---|---|---|---|'];
  const ordered = [...map.entries].sort((a, b) => a.canonical.localeCompare(b.canonical));
  for (const entry of ordered) {
    const old = entry.source ? `\`${routeFor(entry.source)}\`` : '—';
    const link = relativeLink('development/doc-structure.mdx', entry.canonical);
    const note = entry.note ? `：${escapeText(entry.note)}` : '';
    rows.push(`| ${old} | ${OWNER_LABELS[entry.owner]} | [${escapeText(titles.get(entry.canonical))}](${link}) | ${TREATMENT_LABELS[entry.treatment]}${note} |`);
  }
  return rows.join('\n');
}

export async function loadRouteMap(root) {
  return JSON.parse(await readFile(path.join(root, 'project/doc-routes.json'), 'utf8'));
}

export async function renderRoutePages(root) {
  const docs = path.join(root, 'src/content/docs');
  const map = await loadRouteMap(root);
  const titles = new Map();
  for (const entry of map.entries) {
    if (!OWNER_LABELS[entry.owner]) throw new Error(`Unknown owner ${entry.owner} for ${entry.canonical}`);
    if (!TREATMENT_LABELS[entry.treatment]) throw new Error(`Unknown treatment ${entry.treatment} for ${entry.canonical}`);
    if (entry.canonical.split('/')[0] !== entry.owner) throw new Error(`${entry.canonical}: owner must match its top-level section`);
    const fm = frontmatter(await readFile(path.join(docs, entry.canonical), 'utf8'));
    if (fm.unlisted) throw new Error(`${entry.canonical}: canonical page must not be unlisted`);
    titles.set(entry.canonical, fm.title);
  }
  const pages = map.entries.filter(isCompatibility).map(entry => ({
    rel: path.posix.join('src/content/docs', entry.source),
    text: renderCompatibilityPage(entry, titles.get(entry.canonical)),
  }));
  const structureRel = 'src/content/docs/development/doc-structure.mdx';
  const structure = await readFile(path.join(root, structureRel), 'utf8');
  const pattern = new RegExp(`${escapeRegExp(TABLE_BEGIN)}[\\s\\S]*?${escapeRegExp(TABLE_END)}`);
  if (!pattern.test(structure)) throw new Error(`${structureRel}: generated table markers missing`);
  pages.push({ rel: structureRel, text: structure.replace(pattern, `${TABLE_BEGIN}\n\n${renderOwnershipTable(map, titles)}\n\n${TABLE_END}`) });
  return pages;
}

function escapeRegExp(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

async function main() {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const args = process.argv.slice(2);
  if (args.some(a => a !== '--check')) { console.error('Usage: node scripts/sync-doc-routes.mjs [--check]'); process.exitCode = 2; return; }
  const pages = await renderRoutePages(root);
  if (args.includes('--check')) {
    const drifted = [];
    for (const { rel, text } of pages) {
      let current = null;
      try { current = await readFile(path.join(root, rel), 'utf8'); } catch (e) { if (e.code !== 'ENOENT') throw e; }
      if (current !== text) drifted.push(rel);
    }
    if (drifted.length) {
      console.error('Generated route pages differ from project/doc-routes.json:\n' + drifted.map(r => `- ${r}`).join('\n'));
      console.error('Run node scripts/sync-doc-routes.mjs to regenerate them.');
      process.exitCode = 1;
      return;
    }
    console.log(`OK: ${pages.length - 1} compatibility pages and the ownership table match project/doc-routes.json.`);
    return;
  }
  for (const { rel, text } of pages) {
    await mkdir(path.dirname(path.join(root, rel)), { recursive: true });
    await writeFile(path.join(root, rel), text);
  }
  console.log(`Generated ${pages.length - 1} compatibility pages and the ownership table.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(await realpath(process.argv[1])).href) await main();
