#!/usr/bin/env python3
"""Render exact before/after lid CAD with the added ledge material highlighted.

No geometry is generated by this renderer. Both models must be existing STEP
files in assembly coordinates. The added volume is the CAD boolean difference.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import cadquery as cq
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.collections import PolyCollection
from matplotlib.patches import Rectangle
import numpy as np


BG = "#f5f7f8"
INK = "#1c2d36"
MUTED = "#536873"
PART = np.array([0.49, 0.59, 0.63])
ADDITION = np.array([0.09, 0.64, 0.53])
VIEW = np.array([0.10, 1.0, 0.64])
VIEW /= np.linalg.norm(VIEW)
RIGHT = np.cross(VIEW, np.array([0.0, 0.0, 1.0]))
RIGHT /= np.linalg.norm(RIGHT)
UP = np.cross(RIGHT, VIEW)
LIGHT = np.array([-0.25, 0.65, 1.0])
LIGHT /= np.linalg.norm(LIGHT)
ORIGIN = np.array([0.0, -145.0, 98.0])


def project(points):
    points = np.asarray(points) - ORIGIN
    return np.column_stack((points @ RIGHT, points @ UP))


def triangles(shape, color):
    vertices, indices = shape.tessellate(0.03, 0.15)
    pts = np.array([v.toTuple() for v in vertices])
    result = []
    for ids in indices:
        tri = pts[list(ids)]
        normal = np.cross(tri[1] - tri[0], tri[2] - tri[0])
        length = np.linalg.norm(normal)
        if length < 1e-12:
            continue
        normal /= length
        if normal @ VIEW < 1e-7:
            continue
        brightness = 0.68 + 0.32 * max(0.0, float(normal @ LIGHT))
        shade = np.clip(color * brightness, 0, 1)
        result.append((float(tri.mean(0) @ VIEW), project(tri), shade))
    return result


def draw(ax, records, zoom=False):
    records = sorted(records, key=lambda row: row[0])
    collection = PolyCollection([r[1] for r in records],
                                facecolors=[r[2] for r in records],
                                edgecolors="none", antialiased=False)
    ax.add_collection(collection)
    if zoom:
        limits = project([[-58, -145, 94], [58, -145, 116]])
        ax.set_xlim(limits[0, 0], limits[1, 0])
        ax.set_ylim(limits[0, 1] - 1.0, limits[1, 1] + 1.0)
    else:
        all_pts = np.concatenate([r[1] for r in records])
        lo, hi = all_pts.min(0), all_pts.max(0)
        ax.set_xlim(lo[0] - 5, hi[0] + 5)
        ax.set_ylim(lo[1] - 4, hi[1] + 4)
    ax.set_aspect("equal")
    ax.set_facecolor(BG)
    ax.axis("off")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before", type=Path, required=True)
    parser.add_argument("--after", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    before = cq.importers.importStep(str(args.before)).val()
    after = cq.importers.importStep(str(args.after)).val()
    added = after.cut(before)
    before_triangles = triangles(before, PART)
    # Partition the exact additive result into unchanged and added volumes.
    # This avoids coplanar overlays and highlights the actual CAD difference.
    if before.cut(after).Volume() > 1e-6:
        raise ValueError("This comparison expects a purely additive correction.")
    after_triangles = list(before_triangles)
    if added.Volume() > 1e-8:
        after_triangles += triangles(added, ADDITION)

    fig = plt.figure(figsize=(16, 6.2), facecolor=BG)
    for col, records in enumerate([before_triangles, after_triangles]):
        x = [0.045, 0.523][col]
        ax_full = fig.add_axes([x, 0.48, 0.432, 0.28])
        draw(ax_full, records)
        ax_zoom = fig.add_axes([x, 0.20, 0.432, 0.22])
        draw(ax_zoom, records, zoom=True)
        ax_zoom.text(0.0, 1.07, "CENTRE DETAIL", transform=ax_zoom.transAxes,
                     fontsize=9, fontweight="bold", color=MUTED)
    fig.text(0.045, 0.935, "10BOX-v2  /  LID RETAINING LEDGE", color=INK,
             fontsize=22, fontweight="bold")
    fig.text(0.045, 0.891, "Common front / back panel · interior view · exact CAD geometry",
             color=MUTED, fontsize=12)
    fig.text(0.045, 0.827, "BEFORE", color=INK, fontsize=14, fontweight="bold")
    fig.text(0.523, 0.827, "AFTER", color=INK, fontsize=14, fontweight="bold")
    fig.text(0.045, 0.106, "Two obsolete centre gaps", color=MUTED, fontsize=12)
    fig.text(0.523, 0.106, "Connected centre ledge", color=INK, fontsize=12,
             fontweight="bold")
    fig.text(0.523, 0.068, "Green: added material. Outer bracket openings retained.",
             color=MUTED, fontsize=10)
    fig.text(0.045, 0.027, "The front and back use the same part, rotated 180° in the assembly.",
             color=MUTED, fontsize=10)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, dpi=150, facecolor=BG)
    plt.close(fig)
    print(args.out)


if __name__ == "__main__":
    main()
